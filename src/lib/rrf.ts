/**
 * Reciprocal Rank Fusion — слияние результатов полнотекстового и векторного
 * поиска в один список.
 *
 * Считается по местам в списках, а не по их оценкам, и в этом весь смысл:
 * ts_rank и косинусное расстояние живут в разных шкалах, их нельзя ни
 * сравнить, ни сложить напрямую. Нормализовать шкалы пришлось бы подбором
 * коэффициентов под конкретные данные — RRF обходится без калибровки.
 *
 * Вклад места i: 1 / (k + i). Константа k = 60 — общепринятое значение;
 * она сглаживает разрыв между первым и вторым местом, из-за чего заметка,
 * попавшая в середину обоих списков, обгоняет лидера одного-единственного.
 */
export const RRF_K = 60;

export interface FusedItem {
  id: string;
  score: number;
}

/**
 * lists — списки идентификаторов, каждый уже отсортирован по релевантности.
 * Пустые списки допустимы: недоступный внешний API даёт ровно этот случай,
 * и тогда результат вырождается в исходный полнотекстовый порядок.
 */
export function fuseByRrf(
  lists: readonly (readonly string[])[],
  k = RRF_K,
): FusedItem[] {
  const scores = new Map<string, number>();

  for (const list of lists) {
    // Повтор внутри одного списка не должен считаться дважды: место
    // засчитывается по первому вхождению.
    const seen = new Set<string>();

    list.forEach((id, index) => {
      if (seen.has(id)) return;
      seen.add(id);

      scores.set(id, (scores.get(id) ?? 0) + 1 / (k + index + 1));
    });
  }

  return [...scores]
    .map(([id, score]) => ({ id, score }))
    // Порядок при равных очках фиксируем по id: иначе выдача прыгала бы
    // между одинаковыми запросами. Так же сравнивает узлы дерева
    // compareNodes в src/db/queries/tree.ts.
    .sort((a, b) => b.score - a.score || a.id.localeCompare(b.id));
}
