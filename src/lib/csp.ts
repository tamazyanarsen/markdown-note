/**
 * Content-Security-Policy с одноразовым nonce.
 *
 * Зачем вообще: сервис рендерит markdown, написанный человеком, и показывает
 * его по публичной ссылке. Санитизация (src/lib/markdown.ts) — первая линия,
 * CSP — вторая: она нужна ровно на тот случай, если однажды первая пропустит
 * то, чего не должна.
 *
 * Политика собирается здесь, а ставится в src/proxy.ts — nonce обязан быть
 * своим на каждый ответ, а значит его нельзя записать в next.config.ts,
 * где заголовки статичны.
 */

/**
 * Случайный nonce на один ответ.
 *
 * getRandomValues, а не randomUUID: UUID отдаёт 122 бита энтропии в виде
 * 36 символов, здесь те же 128 бит укладываются в 24. Buffer на edge-рантайме
 * не гарантирован, поэтому base64 считается через btoa.
 */
export function generateNonce(): string {
  const bytes = new Uint8Array(16);
  crypto.getRandomValues(bytes);

  return btoa(String.fromCharCode(...bytes));
}

/**
 * Собирает заголовок политики.
 *
 * Вынесено из proxy.ts отдельной чистой функцией, чтобы на неё можно было
 * написать тест: заголовок, собранный конкатенацией строк, легко сломать
 * молча — лишняя точка с запятой или потерянная директива не падают,
 * а просто перестают защищать.
 */
export function buildCsp(nonce: string, isDev: boolean): string {
  const directives = [
    "default-src 'self'",

    // 'strict-dynamic' означает, что доверие переносится с адреса на nonce:
    // скрипт с нашим nonce может подгружать свои чанки, а всё остальное
    // не выполняется, откуда бы ни пришло. Побочный эффект — 'self'
    // в этой директиве браузером игнорируется, и статически отрендеренная
    // страница осталась бы вообще без js: nonce в неё подставить некуда.
    // Поэтому страницы обязаны рендериться на запрос (см. проверку в сборке).
    `script-src 'self' 'nonce-${nonce}' 'strict-dynamic'${
      // В dev React пользуется eval, чтобы показывать серверные стеки
      // в браузере. В проде ни React, ни Next этого не делают.
      isDev ? " 'unsafe-eval'" : ""
    }`,

    // Стили — 'unsafe-inline', и это осознанно, а не «не осилили».
    //
    // Замерено: с nonce вместо него страница даёт 189 отказов. Десять из них
    // — атрибуты style= у React-компонентов, остальные 179 — пустые <style>,
    // которые вставляют в рантайме Radix (react-style-singleton у диалогов),
    // sonner и cmdk. Своего nonce у них нет и взяться ему неоткуда: элемент
    // создаётся на клиенте уже после рендера.
    //
    // Платы за это почти нет. От инъекции css защищает санитизация: из
    // markdown вырезаются и <style>, и атрибут style (см. тесты
    // src/lib/markdown.test.ts). А главное — script-src остаётся строгим,
    // и именно он ловит XSS. Nonce на стилях рядом с обязательным
    // 'unsafe-inline' для тех же стилей был бы украшением, а не защитой.
    "style-src 'self' 'unsafe-inline'",

    // Картинки: свои вложения лежат на своём домене, но в markdown можно
    // вставить и ссылку на чужую — это законный сценарий, а не дыра.
    // Схема data: не нужна: санитизация разрешает у src только http и https.
    "img-src 'self' https:",

    // Шрифты Geist раздаёт next/font со своего домена.
    "font-src 'self'",

    // Весь fetch приложения идёт к себе же. В dev добавляется ws:
    // для горячей перезагрузки.
    `connect-src 'self'${isDev ? " ws:" : ""}`,

    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",

    // Дублирует X-Frame-Options: DENY из next.config.ts. Оба потому,
    // что старые браузеры знают только заголовок, новые — только директиву.
    "frame-ancestors 'none'",
  ];

  // В dev страница открыта по http, и апгрейд ломал бы её локально.
  if (!isDev) directives.push("upgrade-insecure-requests");

  return directives.join("; ");
}
